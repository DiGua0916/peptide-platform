/* Presentation only. The plugin retains native matching and guarded Store API writes. */
(function ($) {
  'use strict';
  if (!$) return;
  const homeProduct = '.vc-home-quick-product';
  const requests = new Map();
  const feedbacks = new WeakMap();
  const pendingOpeners = new Map();
  let openIntent = 0, loadingStatus, stagedRestore = null;
  function stageRestore(item, opener) {
    const entry = {item, opener}; stagedRestore = entry;
    return () => { if (stagedRestore === entry) stagedRestore = null; };
  }
  // Native presenter resets its form immediately before Woo initialization.
  // Set validated reset defaults in capture, before that browser default action;
  // Woo remains the sole owner of variation matching and accepted commerce data.
  document.addEventListener('reset', event => {
    const form = event.target, root = form.closest?.(homeProduct), entry = stagedRestore;
    if (!entry || !root || Number(root.dataset.vcProductId) !== Number(entry.item.productId)) return;
    stagedRestore = null;
    for (const select of form.querySelectorAll('.variations select')) {
      const value = entry.item.attributes?.[select.name];
      if (typeof value !== 'string' || ![...select.options].some(option => option.value === value)) continue;
      for (const option of select.options) option.defaultSelected = option.value === value;
      select.value = value;
    }
    const qty = form.querySelector('input.qty');
    if (qty && /^\d+$/.test(entry.item.quantity || '')) qty.defaultValue = qty.value = String(entry.item.quantity);
    // A product without specifications has no native match to wait for: nothing
    // would ever end the pending state, and its price would stay "Updating price…"
    // with its offers and artwork withheld. Its server-rendered values stand.
    if (!form.querySelector('.variations select')) return;
    // Server/default imagery and discounts must not flash while the restored
    // native match is pending. Normal SKU changes still preserve their artwork.
    clearSelection(form); media(root, null);
  }, true);
  const templateFor = id => document.querySelector('template[data-vc-quick-product="' + id + '"]');
  const canOpen = () => window.HTMLDialogElement && HTMLDialogElement.prototype.showModal && window.fetch && window.AbortController;
  function clearPending() {
    for (const link of pendingOpeners.keys()) link.removeAttribute('aria-busy');
    pendingOpeners.clear();
    if (loadingStatus) loadingStatus.textContent = '';
  }
  function beginPending(link, intent) {
    pendingOpeners.set(link, intent);
    link.setAttribute('aria-busy', 'true');
  }
  function finishPending(link, intent) {
    if (pendingOpeners.get(link) !== intent) return;
    pendingOpeners.delete(link); link.removeAttribute('aria-busy');
  }
  function announce(message) {
    if (!loadingStatus) {
      loadingStatus = document.createElement('span'); loadingStatus.className = 'vc-home-quick__loading-status';
      loadingStatus.setAttribute('role', 'status'); document.body.append(loadingStatus);
    }
    loadingStatus.textContent = message;
  }
  async function loadTemplate(id) {
    if (templateFor(id)) return;
    const existing = requests.get(id);
    if (existing && !existing.controller.signal.aborted) return existing.promise;
    const settings = window.vcHomeQuickView;
    const api = new URL(settings?.productApi || '', location.href);
    if (!settings?.productApi || api.origin !== location.origin || !/^https?:$/.test(api.protocol)) throw new Error('Unavailable product service');
    if (api.searchParams.has('rest_route')) api.searchParams.set('rest_route', api.searchParams.get('rest_route').replace(/\/?$/, '/') + id);
    else api.pathname = api.pathname.replace(/\/?$/, '/') + id;
    const controller = new AbortController();
    const promise = (async () => {
      const timer = setTimeout(() => controller.abort(), 12000);
      try {
        const headers = {Accept: 'application/json'};
        if (settings.wpNonce) headers['X-WP-Nonce'] = settings.wpNonce;
        const response = await fetch(api.href, {credentials: 'same-origin', cache: 'no-store', headers, signal: controller.signal});
        if (!response.ok) throw new Error('Product unavailable');
        const data = await response.json();
        if (String(data.id) !== id || typeof data.html !== 'string') throw new Error('Invalid product response');
        // This HTML is generated by the same-origin native Woo form renderer;
        // keeping it inside a template prevents scripts or forms running here.
        const fragment = document.createElement('template'); fragment.innerHTML = data.html;
        const template = fragment.content.firstElementChild;
        if (fragment.content.children.length !== 1 || template?.tagName !== 'TEMPLATE' ||
            template.dataset.vcQuickProduct !== id ||
            template.content.firstElementChild?.dataset.vcProductId !== id) throw new Error('Invalid product template');
        if (!templateFor(id)) document.body.append(template);
      } finally { clearTimeout(timer); if (requests.get(id)?.controller === controller) requests.delete(id); }
    })();
    requests.set(id, {promise, controller});
    return promise;
  }
  const sameOriginImage = value => {
    try { const url = new URL(value, location.href); return /^https?:$/.test(url.protocol) && url.origin === location.origin ? url.href : ''; }
    catch (_) { return ''; }
  };
  const initial = root => {
    try { return JSON.parse(root.dataset.vcHomeInitial || '{}'); }
    catch (_) { return {}; }
  };
  function media(root, image) {
    if (root.vcExperience) { root.vcExperience.updateMedia(image); return; }
    let area = root.querySelector(':scope > .vc-showcase-quick__media');
    if (!area) { area = document.createElement('div'); area.className = 'vc-showcase-quick__media'; root.prepend(area); }
    const source = image && sameOriginImage(image.src);
    if (!source) {
      const empty = document.createElement('p'); empty.className = 'vc-home-quick__missing';
      empty.textContent = 'Image not available for this specification.'; area.replaceChildren(empty); return;
    }
    let img = area.querySelector('img');
    if (!img) { img = document.createElement('img'); area.replaceChildren(img); }
    img.alt = String(image.alt || root.dataset.vcProductName || '');
    // These fields are generated by Woo/WordPress, not editable catalogue HTML.
    if (image.sizes) img.sizes = image.sizes; else img.removeAttribute('sizes');
    if (image.srcset) { if (img.getAttribute('srcset') !== image.srcset) img.srcset = image.srcset; } else img.removeAttribute('srcset');
    if (Number(image.width) > 0) img.width = Number(image.width);
    if (Number(image.height) > 0) img.height = Number(image.height);
    img.loading = 'eager'; img.decoding = 'async';
    if (img.getAttribute('src') !== source) img.src = source;
  }
  function details(root, sku) {
    const summary = root.querySelector('.summary'); if (!summary) return;
    let skuLine = summary.querySelector('.vc-home-quick__sku');
    if (skuLine) skuLine.hidden = true;
    const detailsLink = summary.querySelector('.vc-showcase-quick__details'); if (detailsLink) detailsLink.hidden = true;
    let selected = summary.querySelector('.vc-home-quick__specification');
    if (!selected) { selected = document.createElement('p'); selected.className = 'vc-home-quick__specification'; summary.querySelector(':scope > .price')?.after(selected); }
    const label = [...summary.querySelectorAll('.variations select')].map(select => select.value ? select.selectedOptions[0]?.textContent : '').filter(Boolean).join(' / ');
    selected.textContent = window.vcProductSpecification?.format(label) || label;
    selected.hidden = !selected.textContent;
  }
  function price(root, markup) {
    const target = root.querySelector('.summary > .price'); if (!target) return;
    // Only server-formatted native variation HTML is accepted here. No client
    // arithmetic, parent range, compare price, or discount is manufactured.
    if (typeof markup === 'string' && markup) {
      const html = markup + '<span class="vc-price-sales-unit"> / box</span>';
      if (target.innerHTML !== html) target.innerHTML = html;
    }
    else target.textContent = root.vcHomeSelectionPending ? 'Updating price…' : 'Choose a specification to see its price.';
    target.setAttribute('aria-live', 'polite'); target.setAttribute('aria-atomic', 'true');
  }
  const selectedAttributes = form => Object.fromEntries([...form.querySelectorAll('.variations select')].map(select => [select.name, select.value]));
  function matchesSelection(form, variation) {
    const selected = selectedAttributes(form), expected = variation?.attributes;
    const keys = Object.keys(selected);
    // Native lookup may finish after the customer has chosen another dosage.
    // A response is presentation data only for its complete current selection.
    return Number.isSafeInteger(Number(variation?.variation_id)) && Number(variation.variation_id) > 0 && expected && keys.length > 0
      && keys.length === Object.keys(expected).length && keys.every(key => selected[key] !== '' && expected[key] === selected[key]);
  }
  function clearSelection(form) {
    const root = form.closest(homeProduct); if (!root) return;
    root.vcHomeSelectionPending = true; root.vcHomeImage = null; root.vcHomeSku = '';
    root.vcHomePromotions = []; root.vcHomePrice = '';
    // Native lookup clears commerce state immediately, but the previous decoded
    // artwork can remain until the new exact variation arrives. Removing its src
    // on every pending event causes a blank frame and needless image selection.
    const values = Object.values(selectedAttributes(form));
    price(root, '');
    if (!values.length || values.some(value => !value)) media(root, null);
    details(root, ''); root.vcExperience?.update();
  }
  function quantity(root) {
    const input = root.querySelector('form.cart input.qty');
    if (!input || input.dataset.vcHomeQuantity) return;
    input.dataset.vcHomeQuantity = '1';
    const wrapper = input.closest('.quantity'); if (!wrapper) return;
    wrapper.classList.add('vc-home-quick__quantity');
    for (const [direction, label] of [[-1, 'Decrease quantity'], [1, 'Increase quantity']]) {
      const button = document.createElement('button'); button.type = 'button';
      button.className = 'vc-home-quick__quantity-button'; button.textContent = direction < 0 ? '−' : '+'; button.setAttribute('aria-label', label);
      button.addEventListener('click', () => {
        if (input.disabled || input.closest('[inert]')) return;
        try { direction < 0 ? input.stepDown() : input.stepUp(); } catch (_) { return; }
        input.dispatchEvent(new Event('change', {bubbles: true}));
      });
      if (direction < 0) input.before(button); else input.after(button);
    }
  }
  function moveTo(dialog, target) {
    if (!target) return;
    const top = target.getBoundingClientRect().top - dialog.getBoundingClientRect().top + dialog.scrollTop - 76;
    dialog.scrollTo({top: Math.max(0, top), behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'instant' : 'smooth'});
    target.setAttribute('tabindex', '-1'); target.focus({preventScroll: true});
  }
  function fullDetails(root, dialog, summary) {
    const content = root.querySelector('.vc-product-dialog-content');
    if (!content) return;
    dialog.classList.add('vc-home-quick--full');
    let toolbar = dialog.querySelector('.vc-home-quick__toolbar');
    if (!toolbar) {
      toolbar = document.createElement('div'); toolbar.className = 'vc-home-quick__toolbar';
      const name = document.createElement('strong'); name.className = 'vc-home-quick__toolbar-name';
      toolbar.append(name);
      for (const [label, selector] of [['Options', '.summary'], ['Details', '.vc-product-dialog-content']]) {
        const button = document.createElement('button'); button.type = 'button'; button.textContent = label;
        button.addEventListener('click', () => moveTo(dialog, dialog.querySelector(homeProduct + ' ' + selector)));
        toolbar.append(button);
      }
      const close = dialog.querySelector('.vc-showcase-quick__close');
      const restoreFocus = document.activeElement === close;
      if (close) toolbar.append(close);
      dialog.prepend(toolbar);
      if (restoreFocus) close.focus({preventScroll: true});
    }
    const toolbarName = toolbar.querySelector('strong');
    if (toolbarName) toolbarName.textContent = root.dataset.vcProductName || 'Product details';
    const link = summary.querySelector('.vc-showcase-quick__details');
    if (link) link.hidden = true;
    if (link?.tagName === 'A') {
      const button = document.createElement('button'); button.type = 'button'; button.className = link.className;
      button.textContent = 'Explore product details ↓';
      button.hidden = true;
      button.addEventListener('click', () => moveTo(dialog, content)); link.replaceWith(button);
    }
    if (!content.querySelector(':scope > .vc-product-dialog-heading')) {
      const heading = document.createElement('h2'); heading.className = 'vc-product-dialog-heading'; heading.textContent = 'A closer look.';
      content.prepend(heading);
    }
    // Keep the plugin-owned status and recovery buttons beside the purchase form,
    // even when its reusable product root is detached and opened again.
    const feedback = feedbacks.get(dialog) || dialog.querySelector('.vc-showcase-quick__feedback');
    if (feedback) {
      feedbacks.set(dialog, feedback);
      const sku = summary.querySelector('.vc-home-quick__sku');
      if (sku) sku.before(feedback); else summary.append(feedback);
    }
    // Native Woo namespaces IDs after variation initialization. Preserve local
    // description anchors without changing the page hash or leaving the dialog.
    if (!content.dataset.vcAnchorsReady) {
      content.dataset.vcAnchorsReady = '1';
      content.addEventListener('click', event => {
        const anchor = event.target.closest('a[href^="#"]'); if (!anchor) return;
        const fragment = anchor.getAttribute('href').slice(1); if (!fragment) return;
        const target = [...content.querySelectorAll('[id]')].find(node => node.id === fragment || node.id.endsWith('-' + fragment));
        if (!target) return;
        event.preventDefault();
        let parent = target.parentElement;
        while (parent && parent !== content) { if (parent.tagName === 'DETAILS') parent.open = true; parent = parent.parentElement; }
        moveTo(dialog, target);
      });
    }
    dialog.scrollTop = 0;
  }
  function present(root, opener) {
    const dialog = root.closest('dialog'); if (!dialog) return;
    root.vcHomeOpener = opener;
    dialog.classList.add('vc-home-quick');
    const summary = root.querySelector('.summary'); if (!summary) return;
    if (!root.querySelector('.vc-home-quick__eyebrow')) {
      const eyebrow = document.createElement('p'); eyebrow.className = 'vc-home-quick__eyebrow'; eyebrow.textContent = 'The VialCove collection'; summary.prepend(eyebrow);
    }
    const buy = summary.querySelector('[data-vc-quick-buy]'); if (buy) buy.textContent = 'Buy now';
    summary.querySelector('.vc-showcase-quick__note')?.remove();
    summary.querySelectorAll('.variations label').forEach(label => { if (summary.querySelectorAll('.variations select').length === 1) label.textContent = 'Choose your specification'; });
    const add = summary.querySelector('.single_add_to_cart_button'); if (add) add.textContent = 'Add to bag';
    const defaults = initial(root); media(root, root.vcHomeImage === undefined ? defaults.image : root.vcHomeImage);
    price(root, root.vcHomePrice === undefined ? defaults.priceHtml : root.vcHomePrice);
    details(root, root.vcHomeSku === undefined ? defaults.sku : root.vcHomeSku); quantity(root);
    fullDetails(root, dialog, summary);
    if (!root.vcExperience && window.createVcProductExperience) root.vcExperience = window.createVcProductExperience(root, dialog);
    root.vcExperience?.update();
    window.VialCoveProductImageWarmup?.start(root.querySelector('form.variations_form'), dialog);
    const cart = dialog.querySelector('.vc-showcase-quick__feedback a');
    if (cart) { cart.classList.add('cart-link'); cart.textContent = 'View shopping bag'; }
    const close = dialog.querySelector('.vc-showcase-quick__close');
    if (close) close.setAttribute('aria-label', 'Close product');
    document.dispatchEvent(new CustomEvent('vc:product-presented', {detail: {root, dialog, productId: Number(root.dataset.vcProductId)}}));
    // Ad pixels: ViewContent (browser + Conversions API, shared event_id) for the product shown.
    document.dispatchEvent(new CustomEvent('pc:view-item', {detail: {productId: Number(root.dataset.vcProductId)}}));
  }
  $(document).on('found_variation.vcHomeQuick', homeProduct + ' .variations_form', function (_, variation) {
    const root = this.closest(homeProduct); if (!root || !variation) return;
    if (!matchesSelection(this, variation)) {
      // A direct native listener may already have mirrored the stale response.
      // Reassert our accepted price instead of allowing the old discount to win.
      price(root, root.vcHomePrice || ''); root.vcExperience?.update(); return;
    }
    root.vcHomeSelectionPending = false;
    root.vcHomeImage = Object.prototype.hasOwnProperty.call(variation, 'vc_home_image') ? variation.vc_home_image : variation.image;
    root.vcHomeSku = variation.sku || '';
    root.vcHomePromotions = variation.vc_home_promotions || [];
    root.vcHomePrice = variation.price_html || '';
    price(root, root.vcHomePrice);
    media(root, root.vcHomeImage); details(root, root.vcHomeSku);
    root.vcExperience?.update();
  });
  $(document).on('woocommerce_variation_select_change.vcHomeQuick', homeProduct + ' .variations_form', function () { clearSelection(this); });
  $(document).on('reset_data.vcHomeQuick hide_variation.vcHomeQuick', homeProduct + ' .variations_form', function () {
    clearSelection(this);
  });
  document.addEventListener('change', event => {
    const select = event.target.closest?.(homeProduct + ' .variations select');
    if (select) clearSelection(select.closest('form'));
  }, true);
  // The page contains lightweight cards. Fetch one native template when needed,
  // then replay the click so the existing plugin owns opening and every write.
  document.addEventListener('click', event => {
    const link = event.target.closest?.('[data-vc-home-product][data-vc-quick-open]');
    if (!link || event.defaultPrevented || event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    const id = link.dataset.vcHomeProduct;
    if (!/^[1-9]\d*$/.test(id) || !canOpen()) return;
    if (stagedRestore?.opener && stagedRestore.opener !== link) stagedRestore = null;
    const intent = ++openIntent;
    clearPending();
    if (!templateFor(id)) {
      event.preventDefault(); event.stopImmediatePropagation();
      beginPending(link, intent); announce('Loading product details…');
      loadTemplate(id).then(() => {
        if (intent !== openIntent || !link.isConnected || document.visibilityState === 'hidden') return;
        announce(''); link.click();
      }).catch(() => {
        if (intent !== openIntent || !link.isConnected || document.visibilityState === 'hidden') return;
        if (!link.href) { announce('Product details could not load. Please try again.'); return; }
        announce('Opening the product page…');
        // A failed read never triggers an add-to-cart attempt or hides the PDP.
        location.assign(link.href);
      }).finally(() => finishPending(link, intent));
      return;
    }
    // A trusted browser click can run microtasks between capture and bubble.
    // Wait for the next task so the native bubble handler has opened the dialog.
    // Lazy .click() replays previously masked this ordering difference.
    window.setTimeout(() => {
      const root = document.querySelector('dialog.vc-showcase-quick[open] > .vc-showcase-quick__body > ' + homeProduct);
      if (root && root.dataset.vcProductId === link.dataset.vcHomeProduct) present(root, link);
    }, 0);
  }, true);
  // Keep the product selection underneath the live bag on every viewport.
  // Only a genuine full-page fallback needs to close this product first.
  document.addEventListener('click', event => {
    const link = event.target.closest?.('.vc-home-quick .vc-showcase-quick__feedback a.cart-link');
    if (link && !event.defaultPrevented && event.button === 0 && !event.metaKey && !event.ctrlKey && !event.shiftKey && !event.altKey) {
      if (!window.VialCoveLiveCart?.canOpen?.()) link.closest('dialog')?.querySelector('.vc-showcase-quick__close')?.click();
    }
  }, true);
  // The shared plugin dialog can also be opened by older showcase modules.
  document.addEventListener('click', event => {
    const link = event.target.closest?.('[data-vc-quick-open]');
    if (link && !link.hasAttribute('data-vc-home-product')) {
      stagedRestore = null;
      ++openIntent;
      clearPending();
      const dialog = document.querySelector('dialog.vc-showcase-quick');
      if (dialog) {
        const feedback = feedbacks.get(dialog); if (feedback) dialog.append(feedback);
        const toolbar = dialog.querySelector('.vc-home-quick__toolbar');
        const close = toolbar?.querySelector('.vc-showcase-quick__close');
        const restoreFocus = document.activeElement === close;
        if (close) dialog.prepend(close);
        toolbar?.remove(); dialog.classList.remove('vc-home-quick', 'vc-home-quick--full');
        if (restoreFocus) close.focus({preventScroll: true});
      }
    }
  });
  const cancelPending = () => { stagedRestore = null; ++openIntent; clearPending(); requests.forEach(request => request.controller.abort()); announce(''); };
  document.addEventListener('vc:product-restore-cancel', cancelPending);
  document.addEventListener('keydown', event => { if (event.key === 'Escape') cancelPending(); });
  document.addEventListener('visibilitychange', () => { if (document.hidden) cancelPending(); });
  window.addEventListener('pagehide', cancelPending);
  // History restoration shares the same read and validated template cache.
  // Consumers cancel their own intent without aborting another consumer's read.
  window.VialCoveHomeQuickView = Object.freeze({loadTemplate, stageRestore});
})(window.jQuery);
